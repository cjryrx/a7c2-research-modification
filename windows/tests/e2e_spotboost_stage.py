"""End-to-end proof of the burst-boost overlay stage, without any real patch.

The stage is data driven, so the plumbing has to be proven before the real bytes
exist.  This script builds a throw-away package whose single span lives in the
unused slack of a CP file (bytes the filesystem never exposes), then proves that
the produced DAT decrypts back to the base plaintext except for exactly that one
byte.

Everything it writes is temporary and is removed afterwards; the package is for
self-test only and must never be flashed.

Usage:
    py windows/tests/e2e_spotboost_stage.py BODYDATA_FL23_200.DAT [workdir]
"""

from __future__ import annotations

import hashlib
import json
import shutil
import struct
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RELEASE = ROOT / "windows" / "runtime" / "release"
sys.path.insert(0, str(RELEASE))

import spotboost_package_200 as spotboost  # noqa: E402

firmware = spotboost.firmware


def fat_geometry(cp: bytes):
    if cp[510:512] != b"\x55\xaa":
        raise SystemExit("CP boot sector signature differs")
    bps, spc, reserved, nfats, rootent, tot16, _, fat16 = \
        struct.unpack_from("<HBHBHHBH", cp, 11)
    fat_off = reserved * bps
    root_off = fat_off + nfats * fat16 * bps
    root_sectors = (rootent * 32 + bps - 1) // bps
    data_off = root_off + root_sectors * bps
    cluster_size = bps * spc
    return dict(bps=bps, spc=spc, fat_off=fat_off, root_off=root_off,
                rootent=rootent, data_off=data_off, cluster_size=cluster_size,
                tot16=tot16, fat16=fat16, raw=cp)


def fat12_get(geo, cluster):
    off = geo["fat_off"] + cluster + cluster // 2
    value = geo["raw"][off] | geo["raw"][off + 1] << 8
    return (value >> 4 if cluster & 1 else value) & 0xFFF


def chain(geo, cluster):
    out = []
    while 2 <= cluster < 0xFF8 and cluster not in out:
        out.append(cluster)
        cluster = fat12_get(geo, cluster)
    return out


def slack_byte(geo):
    """Return (offset_in_cp, extents) for one provably unused byte, or None."""
    for index in range(geo["rootent"]):
        entry = geo["raw"][geo["root_off"] + index * 32:
                            geo["root_off"] + index * 32 + 32]
        if len(entry) < 32 or entry[0] == 0:
            break
        if entry[0] == 0xE5 or entry[11] & 0x08:
            continue
        size = struct.unpack_from("<I", entry, 28)[0]
        cluster = struct.unpack_from("<H", entry, 26)[0]
        if not size:
            continue
        run = chain(geo, cluster)
        if not run:
            continue
        used = size - (len(run) - 1) * geo["cluster_size"]
        slack = geo["cluster_size"] - used
        if slack < 8:
            continue
        at = (geo["data_off"] + (run[-1] - 2) * geo["cluster_size"] + used)
        byte = geo["raw"][at]
        if byte not in (0x00, 0xFF):
            continue
        return at
    return None


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    base = Path(sys.argv[1]).resolve()
    workdir = Path(sys.argv[2]).resolve() if len(sys.argv) > 2 else \
        Path(tempfile.mkdtemp(prefix="spotboost_e2e_"))
    workdir.mkdir(parents=True, exist_ok=True)
    spec_data = spotboost.spec_data()
    base_sha = firmware.sha_file(base)
    entry = spotboost.base_for(base_sha, spec_data)
    if entry is None:
        raise SystemExit("base package is not declared by patches_spotboost.json")

    plain = workdir / "plain.bin"
    print("decrypting base ...", flush=True)
    layout = firmware.parse_dat(base)
    with plain.open("xb") as stream:
        for block in firmware.decoded_blocks(base, layout):
            stream.write(block)
    try:
        p15, p5, p8, listing = firmware.tar_parts(plain)
        with plain.open("rb") as stream:
            stream.seek(p8.offset_data)
            cp = bytearray(stream.read(p8.size))
        geo = fat_geometry(cp)
        at = slack_byte(geo)
        if at is None:
            raise SystemExit("no CP file with a usable slack byte")
        old_byte = cp[at]
        new_byte = 0x01 if old_byte == 0x00 else 0x00
        absolute = p8.offset_data + at
        with plain.open("rb") as stream:
            stream.seek(absolute - 64)
            context = stream.read(64 + 80)
        print("span: cp+0x%x %02x -> %02x (file slack)" % (at, old_byte, new_byte),
              flush=True)

        spec = {"format": 1, "id": spotboost.FEATURE_ID, "status": "ready",
                "title": "self test",
                "note": "generated by e2e_spotboost_stage.py; never flash this",
                "bases": [dict(entry)],
                "expected_byte_changes": {"cp": 1},
                "spans": [{"name": "e2e_slack_byte", "partition": "cp",
                           "offset": at,
                           "old_sha256": hashlib.sha256(bytes([old_byte])).hexdigest(),
                           "new": f"{new_byte:02x}",
                           "context_size": len(context),
                           "context_sha256": hashlib.sha256(context).hexdigest(),
                           "why": "self test: unused FAT slack byte"}]}
        spec_path = workdir / "e2e_spotboost_spec.json"
        spec_path.write_text(json.dumps(spec, indent=2), encoding="utf-8")

        print("preflight ...", flush=True)
        proof = spotboost.preflight(base, spec_path)
        print("  ", json.dumps(proof, sort_keys=True))
        if proof["byte_changes"] != {"usr": 0, "wbi": 0, "cp": 1}:
            raise SystemExit("preflight byte accounting differs: %r" % proof)

        outdir = workdir / "out"
        outdir.mkdir(exist_ok=True)
        print("building overlay package ...", flush=True)
        output, report = spotboost.build(base, outdir, spec_path)
        if report["byte_changes"] != {"usr": 0, "wbi": 0, "cp": 1}:
            raise SystemExit("overlay byte accounting differs: %r"
                             % report["byte_changes"])

        print("diffing full decrypt against the base plaintext ...", flush=True)
        # Two kinds of difference are legitimate: the patched byte itself, and
        # the ASCII CRC field of a changed partition inside part_image.sum.
        listing_lo = listing.offset_data
        listing_hi = listing.offset_data + listing.size
        diffs = []
        inside_listing = []
        index = 0
        with plain.open("rb") as expected:
            for block in firmware.decoded_blocks(output, layout):
                chunk = expected.read(len(block))
                if chunk == block:
                    index += len(block)
                    continue
                for i, (a, b) in enumerate(zip(chunk, block)):
                    if a != b:
                        position = index + i
                        if listing_lo <= position < listing_hi:
                            inside_listing.append(position)
                        else:
                            diffs.append(position)
                index += len(block)
        if diffs != [absolute]:
            raise SystemExit("unexpected differing bytes: %r (wanted [%d])"
                             % (diffs[:8], absolute))
        if not inside_listing:
            raise SystemExit("partition checksum text was not refreshed")
        print("PASS: output differs in the patched byte (0x%x) and %d CRC "
              "characters inside part_image.sum" % (absolute, len(inside_listing)),
              flush=True)
        print("  output sha256:", report["output_sha256"])
        return 0
    finally:
        shutil.rmtree(workdir, ignore_errors=True)


if __name__ == "__main__":
    raise SystemExit(main())
